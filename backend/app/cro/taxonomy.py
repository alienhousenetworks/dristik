def _item(key: str, label: str, need: str = "crawl", models: str = "*") -> Tuple[str, str, str, str]:
    return (key, need, models, label)


def _section(number: int, part: str, title: str, specialist: str, items: List[Tuple[str, str, str, str]]) -> Dict[str, Any]:
    return {
        "number": number,
        "part": part,
        "title": title,
        "specialist": specialist,
        "items": items,
    }


