def catalog() -> List[Dict[str, Any]]:
    """Return the 55 sections with stable check ids."""
    sections: List[Dict[str, Any]] = []
    for section in _SECTIONS:
        checks = []
        for index, (key, need, models, label) in enumerate(section["items"], start=1):
            checks.append({
                "check_id": f"CRO-S{section['number']:02d}-{index:02d}",
                "section": section["number"],
                "part": section["part"],
                "section_title": section["title"],
                "specialist": section["specialist"],
                "key": key,
                "need": need,
                "models": models,
                "label": label,
            })
        sections.append({
            "number": section["number"],
            "part": section["part"],
            "title": section["title"],
            "specialist": section["specialist"],
            "checks": checks,
        })
    return sections
