"""Master SEO report taxonomy. Chapters are the table of contents, not a claim that every check applies."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Subchapter:
    subchapter_id: str
    title: str


@dataclass(frozen=True)
class Chapter:
    number: int
    title: str
    part: str
    purpose: str
    subchapters: tuple[Subchapter, ...]


def _subs(pairs: list[tuple[str, str]]) -> tuple[Subchapter, ...]:
    return tuple(Subchapter(subchapter_id=sid, title=title) for sid, title in pairs)


