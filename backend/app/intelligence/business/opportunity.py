"""
Dristik AI Opportunity Detection Engine
Discovers high-conviction growth opportunities, content expansion vectors,
and competitive whitespace alongside defect remediation.
"""
from typing import List, Dict, Any
from pydantic import BaseModel, Field
from app.mission.state import Opportunity
from app.domain.models import BusinessProfile, PageEvidence, Claim

class OpportunityDetector:
    """
    Identifies high-leverage commercial and organic expansion opportunities.
    """

    def detect_opportunities(
        self,
        business_profile: BusinessProfile,
        pages: List[PageEvidence],
        claims: List[Claim]
    ) -> List[Opportunity]:
        opportunities: List[Opportunity] = []
        name = business_profile.business_name
        niche = business_profile.niche
        crawled_urls = [p.url.lower() for p in pages]

        # 1. Topic Cluster Opportunity
        has_blog = any(any(k in u for k in ["blog", "insights", "resources", "articles"]) for u in crawled_urls)
        if not has_blog or len(pages) < 10:
            opportunities.append(Opportunity(
                id="opp_01_topic_cluster",
                title=f"Build Authority Topic Cluster around '{niche}'",
                description="Create a dedicated informational topic cluster addressing common enterprise operational questions.",
                domain="CONTENT_SEO",
                opportunity_score=None,
                strategic_value="High",
                effort_level="Medium",
                expected_impact="Captures top-of-funnel buyer intent and establishes primary entity relevance for search engines.",
                action_plan="Publish pillar articles with structured Schema.org Article markup."
            ))

        # 2. Transparent Enterprise Pricing / ROI Calculator
        has_pricing = any("pricing" in u for u in crawled_urls)
        if not has_pricing:
            opportunities.append(Opportunity(
                id="opp_02_transparent_pricing",
                title="Launch Transparent Pricing & Commercial Tier Matrix",
                description="Publish an accessible pricing page with plan tier comparisons and direct sales qualification CTAs.",
                domain="CONVERSION_CRO",
                opportunity_score=None,
                strategic_value="Critical",
                effort_level="Low",
                expected_impact="Reduces buyer qualification friction and provides transparent commercial signals.",
                action_plan="Deploy pricing matrix with clear feature breakdowns, FAQ schema, and direct booking CTA."
            ))

        # 3. Generative Engine Optimization (GEO) & Schema Moat
        has_schema = any(len(p.schema_types) > 0 for p in pages)
        if not has_schema:
            opportunities.append(Opportunity(
                id="opp_03_geo_schema",
                title="Implement Structured JSON-LD Knowledge Graph Injection",
                description="Inject Organization, SoftwareApplication, and FAQPage schemas across all primary routes.",
                domain="GEO_AI_SEARCH",
                opportunity_score=None,
                strategic_value="Critical",
                effort_level="Low",
                expected_impact="Improves entity extractability and Knowledge Graph resolution across search and AI answer engines.",
                action_plan="Deploy validated Schema.org snippets generated by Dristik Remediation Engine."
            ))

        return opportunities
